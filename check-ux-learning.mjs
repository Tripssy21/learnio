import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { createStore } = require('./learning-store.js');
const { QUESTIONS } = require('./server.js');

const values = new Map();
const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
let clock = new Date('2026-10-08T06:00:00Z');
const create = () => createStore({ storage, now: () => clock, seed: true, questions: QUESTIONS });
let store = create();
const ok = result => { assert.equal(result.ok, true, result.error); return result; };
const rejected = (action, pattern) => {
  const before = store.getState(), result = action();
  assert.equal(result.ok, false);
  if (pattern) assert.match(result.error, pattern);
  assert.deepEqual(store.getState(), before, 'Rejected operations preserve every record and revision.');
};
const available = hours => ({ weeklyHours: hours * 7, days: Object.fromEntries(Array.from({ length: 7 }, (_, day) => [day, hours])), startTime: '18:00', timezone: 'Asia/Kolkata' });
ok(await store.login('riya_learns', 'demo123'));

const beforePreview = store.getState();
const fields = { entryId: 'dsa-journey', title: 'My feasible plan', startDate: store.today(), availability: available(1), targetWeeks: 1 };
const preview = ok(store.previewJourney(fields));
assert.equal(preview.targetDate, store.plusDays(store.today(), 6));
assert.equal(preview.finishDate, preview.tasks.at(-1).date, 'Estimated finish is the actual last allocation, not the week end.');
assert.ok(preview.tasks.every(t => t.title && t.type && t.topic), 'The session preview names the actual content.');
assert.deepEqual(store.getState(), beforePreview, 'Preview cannot persist or select a journey.');
assert.ok(store.previewJourney({ ...fields, entryId: 'array-sheet' }).ok, 'Course and sheet first-use selections use the same preview.');
assert.ok(store.previewJourney({ ...fields, entryId: 'python-course' }).ok);
rejected(() => store.adoptJourney('dsa-journey', { ...fields, availability: available(.1) }), /target/);
assert.equal(store.previewJourney({ ...fields, availability: available(.1) }).ok, false);
const extendedPreview = ok(store.previewJourney({ ...fields, availability: available(.1), allowLaterFinish: true }));
assert.equal(extendedPreview.targetExceeded, true);
assert.ok(extendedPreview.warnings.some(w => w.includes('target')));
const adoptedId = ok(store.adoptJourney('dsa-journey', fields)).journeyId;
store = create();
const adopted = store.getJourney(adoptedId);
assert.equal(adopted.title, fields.title);
assert.equal(adopted.targetWeeks, 1);
assert.equal(adopted.targetDate, preview.targetDate);
assert.equal(adopted.finishDate, preview.finishDate);
assert.equal(adopted.sourceVersion.id, 'dsa-journey');
const lastTask = store.getTasks(adoptedId).at(-1);
rejected(() => store.rescheduleTask(adoptedId, lastTask.id, store.plusDays(adopted.targetDate, 1), '18:00'), /target/);
rejected(() => store.scheduleQuiz({ journeyId: adoptedId, topics: ['Arrays'], date: store.plusDays(adopted.targetDate, 1), startTime: '18:00', minutes: 10 }), /target/);
rejected(() => store.saveSchedule(adoptedId, available(.1)), /target/);
ok(store.saveSchedule(adoptedId, { ...available(.1), allowLaterFinish: true }));
assert.equal(store.getJourney(adoptedId).allowLaterFinish, true);
assert.equal(store.getJourney(adoptedId).targetWeeks, 1);
assert.ok(store.getJourney(adoptedId).finishDate > adopted.targetDate);
rejected(() => store.createJourney({ title: 'Invalid target', targetWeeks: 1.5 }), /whole weeks/);
rejected(() => store.createJourney({ title: 'Invalid target type', targetWeeks: true }), /target/);

const slicesId = ok(store.createJourney({ title: 'Session-aware study', contentIds: ['dsa-course', 'array-sheet'], availability: available(.25), targetWeeks: 8 })).journeyId;
const lesson = store.getJourney(slicesId).items.find(i => i.type === 'lesson');
const lessonTasks = store.getTasks(slicesId).filter(t => t.itemId === lesson.id);
assert.ok(lessonTasks.length > 1);
ok(store.completeTask(slicesId, lessonTasks[0].id, { note: 'First session only', url: 'https://example.test/evidence' }));
assert.equal(store.getJourney(slicesId).items.find(i => i.id === lesson.id).completedAt, null);
assert.equal(store.getTasks(slicesId).filter(t => t.itemId === lesson.id && t.completedAt).length, 1);
assert.equal(store.getJourney(slicesId).items.find(i => i.id === lesson.id).note, 'First session only');
assert.equal(store.getEvidence(slicesId).at(-1).source, 'module');
const evidenceCount = store.getEvidence(slicesId).length;
ok(store.completeTask(slicesId, lessonTasks[0].id));
assert.equal(store.getEvidence(slicesId).length, evidenceCount, 'Repeated completion does not create duplicate evidence.');
ok(store.completeItem(slicesId, lesson.id, { note: 'Finished the full lesson' }));
assert.ok(store.getTasks(slicesId).filter(t => t.itemId === lesson.id).every(t => t.completedAt));
const problem = store.getJourney(slicesId).items.find(i => i.type === 'problem');
const problemTask = store.getTasks(slicesId).find(t => t.itemId === problem.id);
ok(store.completeTask(slicesId, problemTask.id, { note: 'Partial problem practice' }));
assert.equal(store.getEvidence(slicesId).at(-1).source, 'manual');
assert.equal(store.getJourney(slicesId).items.find(i => i.id === problem.id).completedAt, null);
const studyId = ok(store.addStudyReference(slicesId, { title: 'Prepare for arrays assignment', topic: 'Arrays', minutes: 15, reference: { courseId: 'official-course', assignmentId: 'official-assignment' }, content: 'Official body must not be copied' })).itemId;
const study = store.getJourney(slicesId).items.find(i => i.id === studyId);
assert.equal(study.type, 'review');
assert.equal(study.content, '');
assert.deepEqual(study.studyReference, { courseId: 'official-course', assignmentId: 'official-assignment' });
ok(store.completeTask(slicesId, store.getTasks(slicesId).find(t => t.itemId === studyId).id));
assert.equal(store.getEvidence(slicesId).at(-1).source, 'manual', 'Preparation completion is a private record, not an official submission.');
rejected(() => store.addStudyReference(slicesId, { title: 'Bad reference', topic: 'Arrays', minutes: 15, reference: { courseId: 'official-course', assignmentId: 'a', materialId: 'm' } }), /one course/);
rejected(() => store.addStudyReference(slicesId, { title: 'Bad source', topic: 'Arrays', minutes: 15, reference: { courseId: 'official-course', materialId: 'm' }, sourceUrl: 'javascript:alert(1)' }), /http/);

const quizDate = store.plusDays(store.today(), 30);
const quizId = ok(store.scheduleQuiz({ journeyId: slicesId, topics: ['Arrays'], date: quizDate, startTime: '18:00', minutes: 10 })).itemId;
const originalQuizTask = store.getTasks(slicesId).find(t => t.itemId === quizId);
const overlap = store.getTasks(slicesId).find(t => t.itemId !== quizId && !t.completedAt);
rejected(() => store.updateScheduledQuiz(slicesId, quizId, { date: overlap.date, startTime: overlap.startTime }), /overlap/);
ok(store.updateScheduledQuiz(slicesId, quizId, { date: store.plusDays(quizDate, 1), minutes: 15 }));
const movedQuizTask = store.getTasks(slicesId).find(t => t.itemId === quizId);
assert.equal(movedQuizTask.id, originalQuizTask.id, 'Editing preserves scheduled item and task identity.');
assert.equal(movedQuizTask.minutes, 15);
assert.equal(store.getJourney(slicesId).items.find(i => i.id === quizId).duration, 15);
ok(store.updateScheduledQuiz(slicesId, quizId, { startTime: '19:00' }));
assert.ok(store.getJourney(slicesId).scheduleWarnings.some(w => w.includes('outside')));
ok(store.updateScheduledQuiz(slicesId, quizId, { startTime: '18:00' }));
assert.equal(store.getJourney(slicesId).scheduleWarnings.length, 0, 'Editing recomputes warnings rather than keeping stale dates.');
const scheduledAttempt = ok(store.startQuiz({ journeyId: slicesId, itemId: quizId })).attemptId;
ok(store.answerQuiz(scheduledAttempt, store.getAttempt(scheduledAttempt).questions[0].id, 0));
rejected(() => store.updateScheduledQuiz(slicesId, quizId, { minutes: 10 }), /open attempt/);
const totalBeforeCancel = store.getStats(slicesId).total;
ok(store.cancelScheduledQuiz(slicesId, quizId));
assert.equal(store.getAttempt(scheduledAttempt).status, 'abandoned');
assert.ok(Object.keys(store.getAttempt(scheduledAttempt).answers).length, 'Cancelling retains saved attempt answers.');
assert.ok(store.getJourney(slicesId).items.find(i => i.id === quizId).cancelledAt);
assert.ok(store.getJourney(slicesId).tasks.find(t => t.id === originalQuizTask.id).cancelledAt);
assert.equal(store.getTasks(slicesId).some(t => t.itemId === quizId), false);
assert.equal(store.getStats(slicesId).total, totalBeforeCancel - 1);
assert.equal(store.getActivityYear(2026, slicesId).days.find(d => d.date === movedQuizTask.date).plannedMinutes, 0);
rejected(() => store.startQuiz({ journeyId: slicesId, itemId: quizId }), /cancelled/);
ok(store.cancelScheduledQuiz(slicesId, quizId));
ok(store.saveSchedule(slicesId, available(.25)));
assert.ok(store.getJourney(slicesId).tasks.find(t => t.id === originalQuizTask.id).cancelledAt, 'Reallocation preserves cancellation history.');
const completedQuizId = ok(store.scheduleQuiz({ journeyId: slicesId, topics: ['Arrays'], date: movedQuizTask.date, startTime: '18:00', minutes: 15 })).itemId;
const completedAttempt = ok(store.startQuiz({ journeyId: slicesId, itemId: completedQuizId })).attemptId;
const completedQuestion = store.getAttempt(completedAttempt).questions[0];
ok(store.answerQuiz(completedAttempt, completedQuestion.id, completedQuestion.answer));
ok(store.submitQuiz(completedAttempt));
rejected(() => store.cancelScheduledQuiz(slicesId, completedQuizId), /Completed/);
rejected(() => store.updateScheduledQuiz(slicesId, completedQuizId, { minutes: 10 }), /Completed/);

const untimedId = ok(store.startQuiz({ journeyId: slicesId, topics: ['Arrays'], minutes: 0 })).attemptId;
assert.equal(store.getAttempt(untimedId).expiresAt, null);
clock = new Date(clock.getTime() + 3 * 86400000);
const untimedQuestion = store.getAttempt(untimedId).questions[0];
ok(store.answerQuiz(untimedId, untimedQuestion.id, untimedQuestion.answer));
ok(store.submitQuiz(untimedId));
assert.equal(store.getAttempt(untimedId).expired, false);
assert.equal(store.getAttempt(untimedId).timeUsedSeconds, 3 * 86400);
const timedId = ok(store.startQuiz({ journeyId: slicesId, topics: ['Arrays'], minutes: 10 })).attemptId;
const timedQuestion = store.getAttempt(timedId).questions[0];
clock = new Date(clock.getTime() + 11 * 60000);

ok(store.abandonQuiz(timedId));

ok(store.updateJourney(slicesId, { status: 'paused' }));
rejected(() => store.completeTask(slicesId, overlap.id), /Reactivate|paused|active|before/);
rejected(() => store.scheduleQuiz({ journeyId: slicesId, topics: ['Arrays'], date: quizDate, minutes: 10 }), /Reactivate|paused|active|before/);
rejected(() => store.cancelScheduledQuiz(slicesId, quizId), /Reactivate|paused|active|before/);
ok(store.updateJourney(slicesId, { status: 'active' }));

import assert from 'node:assert/strict';
import academy from './academy.js';

const users = [['student', false], ['classmate', false], ['teacher', true], ['admin', false], ['outside', false]].map(([id, educator]) => ({ id, username: id, displayName: id, educator }));
const state = { users, reservedUsernames: [], userData: Object.fromEntries(users.map(u => [u.id, { journeys: [], memberships: [] }])) };
for (const [id, role] of [['student', 'student'], ['classmate', 'student'], ['teacher', 'educator'], ['admin', 'administrator']]) state.userData[id].memberships.push({ institutionId: 'northstar', institutionName: 'Northstar College', role, status: 'active', courseIds: id === 'classmate' ? [] : ['cs-201'] });
academy.seed(state, ['student', 'teacher', 'admin']);
const run = (actor, action, input) => academy.action(state, actor, action, [input]);
const success = (actor, action, input) => { const result = run(actor, action, input); assert.equal(result.ok, true, `${action}: ${result.error}`); return result; };
const denied = (actor, action, input) => assert.equal(run(actor, action, input).ok, false, `${action} should be rejected`);
const semesterInput = { institutionId: 'northstar', title: 'Semester 3 · Autumn', academicYear: '2026–27', startDate: '2026-08-01', endDate: '2026-12-20', status: 'current' };
denied('student', 'createSemester', semesterInput);
const current = success('admin', 'createSemester', semesterInput).semesterId;
denied('admin', 'createSemester', { ...semesterInput, startDate: '2026-02-30' });
denied('admin', 'createSemester', { ...semesterInput, endDate: '2026-07-31' });
assert.equal(state.academy.semesters.find(s => s.id === current).status, 'current');
const next = success('admin', 'createSemester', { ...semesterInput, title: 'Semester 4 · Spring', startDate: '2027-01-05', endDate: '2027-05-20', status: 'upcoming' }).semesterId;
success('admin', 'updateSemester', { ...semesterInput, semesterId: next, title: 'Semester 4 · Spring', startDate: '2027-01-05', endDate: '2027-05-20' });
assert.equal(state.academy.semesters.filter(s => s.status === 'current').length, 1);
assert.equal(state.academy.semesters.find(s => s.id === current).status, 'completed');
success('admin', 'updateSemester', { ...semesterInput, semesterId: current });
assert.equal(academy.snapshot(state, 'student').institutions[0].currentSemesterId, current);

const otherInstitution = success('outside', 'createInstitution', { name: 'Another College', username: 'another_college' }).institutionId;
const foreignSemester = success('outside', 'createSemester', { ...semesterInput, institutionId: otherInstitution }).semesterId;
success('admin', 'createProgram', { institutionId: 'northstar', title: 'B.Tech Computer Science', description: 'Undergraduate degree' });
const programId = state.academy.programs.at(-1).id;
success('outside', 'createDepartment', { institutionId: otherInstitution, title: 'Other Department' });
const foreignDepartment = state.academy.departments.at(-1).id;
const courseInput = { courseId: 'cs-201', title: 'Data Structures', description: 'Core structures course.', code: 'CS201', credits: 4, kind: 'core', semesterId: current, departmentId: 'computing', programId };
success('admin', 'updateCourse', courseInput);
denied('student', 'updateCourse', courseInput);
denied('admin', 'updateCourse', { ...courseInput, semesterId: foreignSemester });
denied('admin', 'createCourse', { ...courseInput, institutionId: 'northstar', departmentId: foreignDepartment });
const elective = success('admin', 'createCourse', { ...courseInput, institutionId: 'northstar', title: 'Open elective', code: 'EL301', kind: 'elective' }).courseId;
const studentCourses = academy.snapshot(state, 'student');
assert.equal(studentCourses.courses.length, 1);
assert.equal(studentCourses.courses[0].isCurrentSemester, true);
assert.equal(studentCourses.courses[0].isEnrolled, true);
const offered = studentCourses.courseCatalogue.find(c => c.id === elective);
assert.equal(offered.canAccess, false);
assert.equal(offered.isEnrolled, false);
assert.equal(offered.materials, undefined);
assert.equal(offered.learnerIds, undefined);
assert.equal(offered.ownerId, undefined);
assert.equal(academy.snapshot(state, 'outside').courseCatalogue.some(c => c.id === elective), false);

const academic = { institutionId: 'northstar', userId: 'student', rollNumber: '26CS101', departmentId: 'computing', programId, semesterId: current, admissionYear: 2025, section: 'A', advisor: 'Prof. Asha Rao' };
success('admin', 'updateAcademicProfile', academic);
denied('student', 'updateAcademicProfile', { ...academic, section: 'B' });
denied('admin', 'updateAcademicProfile', { ...academic, userId: 'outside' });
denied('admin', 'updateAcademicProfile', { ...academic, semesterId: foreignSemester });
denied('admin', 'updateAcademicProfile', { ...academic, userId: 'classmate' });
denied('admin', 'updateAcademicProfile', { ...academic, admissionYear: 2025.5 });
const studentProfile = academy.snapshot(state, 'student');
assert.equal(studentProfile.institutions[0].profile.rollNumber, academic.rollNumber);
assert.equal(studentProfile.institutions[0].profile.section, 'A');
assert.equal(studentProfile.academicProfiles.length, 1);
assert.equal(academy.snapshot(state, 'admin').academicProfiles.length, 4);
assert.equal(academy.snapshot(state, 'outside').academicProfiles.length, 1);

const eventInput = { institutionId: 'northstar', scope: 'campus', type: 'holiday', title: 'Campus holiday', description: 'College closed.', startDate: '2026-10-02', endDate: '2026-10-03', location: 'Campus', semesterId: current };
denied('student', 'createCalendarEvent', eventInput);
denied('teacher', 'createCalendarEvent', eventInput);
denied('outside', 'createCalendarEvent', eventInput);
denied('admin', 'createCalendarEvent', { ...eventInput, semesterId: foreignSemester });
denied('admin', 'createCalendarEvent', { ...eventInput, startDate: '2026-02-30' });
denied('student', 'createCalendarEvent', { ...eventInput, scope: 'personal', startTime: '25:00' });
const campus = success('admin', 'createCalendarEvent', eventInput).eventId;
const personal = success('student', 'createCalendarEvent', { ...eventInput, scope: 'personal', type: 'meeting', userId: 'teacher', title: 'Advisor appointment', startTime: '14:30' }).eventId;
assert.equal(state.academy.calendarEvents.find(e => e.id === personal).userId, 'student');
assert.deepEqual(academy.snapshot(state, 'student').calendarEvents.map(e => e.id), [campus, personal]);
assert.deepEqual(academy.snapshot(state, 'teacher').calendarEvents.map(e => e.id), [campus]);
assert.deepEqual(academy.snapshot(state, 'admin').calendarEvents.map(e => e.id), [campus]);
assert.equal(academy.snapshot(state, 'outside').calendarEvents.length, 0);
denied('student', 'deleteCalendarEvent', { eventId: campus });
denied('admin', 'deleteCalendarEvent', { eventId: personal });
success('student', 'deleteCalendarEvent', { eventId: personal });
assert.equal(academy.snapshot(state, 'student').calendarEvents.length, 1);
success('admin', 'deleteCalendarEvent', { eventId: campus });

const noticeInput = { institutionId: 'northstar', title: 'Course registration', body: 'Register before the deadline.', category: 'academic', audience: 'all', priority: 'important', office: 'Academic Office', reference: 'AC/2026/13', attachmentUrl: 'https://example.org/notice.pdf', expiresAt: '2026-10-20' };
const all = success('admin', 'announce', noticeInput).announcementId;
const students = success('admin', 'announce', { ...noticeInput, audience: 'students' }).announcementId;
const teachers = success('admin', 'announce', { ...noticeInput, audience: 'educators' }).announcementId;
const department = success('admin', 'announce', { ...noticeInput, audience: 'department', targetId: 'computing' }).announcementId;
const program = success('admin', 'announce', { ...noticeInput, audience: 'program', targetId: programId }).announcementId;
const course = success('teacher', 'announce', { ...noticeInput, audience: 'course', targetId: 'cs-201' }).announcementId;
const hiddenElective = success('admin', 'announce', { ...noticeInput, audience: 'course', targetId: elective }).announcementId;
denied('teacher', 'announce', noticeInput);
denied('teacher', 'announce', { ...noticeInput, audience: 'course', targetId: elective });
denied('student', 'announce', { ...noticeInput, audience: 'course', targetId: 'cs-201' });
denied('admin', 'announce', { ...noticeInput, audience: 'department', targetId: foreignDepartment });
denied('admin', 'announce', { ...noticeInput, attachmentUrl: 'javascript:alert(1)' });
denied('admin', 'announce', { ...noticeInput, expiresAt: '2026-02-30' });
assert.deepEqual(academy.snapshot(state, 'student').announcements.map(a => a.id), [all, students, department, program, course]);
assert.deepEqual(academy.snapshot(state, 'classmate').announcements.map(a => a.id), [all, students]);
assert.deepEqual(academy.snapshot(state, 'teacher').announcements.map(a => a.id), [all, teachers, course]);
assert.equal(academy.snapshot(state, 'admin').announcements.length, 7);
assert.equal(academy.snapshot(state, 'outside').announcements.length, 0);
denied('student', 'markAnnouncementRead', { announcementId: hiddenElective });
success('student', 'markAnnouncementRead', { announcementId: all });
success('student', 'markAnnouncementRead', { announcementId: all });
assert.equal(state.userData.student.memberships[0].announcementReadIds.length, 1);
assert.equal(academy.snapshot(state, 'student').announcements.find(a => a.id === all).isRead, true);
assert.equal(academy.snapshot(state, 'teacher').announcements.find(a => a.id === all).isRead, false);
denied('student', 'archiveAnnouncement', { announcementId: all });
success('teacher', 'archiveAnnouncement', { announcementId: course });
assert.ok(academy.snapshot(state, 'student').announcements.find(a => a.id === course).archivedAt);
assert.equal(academy.snapshot(state, 'classmate').announcements.some(a => a.id === course), false);
assert.ok(academy.snapshot(state, 'teacher').announcements.find(a => a.id === course).archivedAt);
success('admin', 'archiveAnnouncement', { announcementId: all });
assert.ok(academy.snapshot(state, 'student').announcements.find(a => a.id === all).archivedAt);
success('student', 'markAnnouncementRead', { announcementId: all });

const scheduled = success('teacher', 'createClass', { courseId: 'cs-201', title: 'Arrays lab', startAt: '2026-10-05T10:00:00.000Z', minutes: 60, location: 'CS Lab 2', classType: 'lab' });
assert.ok(scheduled.ok);
assert.equal(academy.snapshot(state, 'student').classes.at(-1).location, 'CS Lab 2');
assert.equal(academy.snapshot(state, 'classmate').classes.length, 0);
state.userData.student.memberships[0].status = 'revoked';
const revoked = academy.snapshot(state, 'student');
assert.equal(revoked.semesters.length, 0);
assert.equal(revoked.calendarEvents.length, 0);
assert.equal(revoked.announcements.length, 0);
assert.equal(revoked.courseCatalogue.length, 0);
assert.equal(revoked.academicProfiles.length, 0);
denied('student', 'createCalendarEvent', { ...eventInput, scope: 'personal' });
console.log('College checks passed: semester rollover, selective enrollment, catalogue privacy, official profile permissions, campus/personal calendars, notice audiences, read isolation, archival, and revoked access.');

import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import vm from 'node:vm';
const require=createRequire(import.meta.url),CSV=require('./csv.js');
const source=readFileSync(new URL('./app.js',import.meta.url),'utf8');
const code=source.slice(source.indexOf('function enrollmentImportCsv('),source.indexOf('function enrollmentImportDialog('));
const context=vm.createContext({window:{LearnioCSV:CSV}});vm.runInContext(code,context);
const form={elements:{csv:{value:'username,role\n"learner_one",student\nteacher_one,educator'},courseId:{value:'offering-2026'},advanced:{checked:false}}};
assert.deepEqual(CSV.parse(context.enrollmentImportCsv(form)),[['username','courseId','role'],['learner_one','offering-2026','student'],['teacher_one','offering-2026','educator']]);
form.elements.courseId.value='other-offering';
assert.equal(CSV.parse(context.enrollmentImportCsv(form))[1][1],'other-offering','The selected offering scopes every cohort row.');
form.elements.csv.value='username,courseId,role\nlearner_one,course-a,student';
assert.throws(()=>context.enrollmentImportCsv(form),/Advanced/,'Mixed scopes cannot silently override a per-row course.');
form.elements.advanced.checked=true;
assert.equal(context.enrollmentImportCsv(form),form.elements.csv.value,'Advanced multi-course intake retains explicit row scopes.');
form.elements.advanced.checked=false;form.elements.csv.value='username\nlearner_one';
assert.throws(()=>context.enrollmentImportCsv(form),/username,role/);
form.elements.csv.value='username,role\n"unterminated,student';
assert.throws(()=>context.enrollmentImportCsv(form),/not closed/);
console.log('Enrollment UI checks passed: one-offering scope, multi-course opt-in, and shared CSV validation.');
